// Promote the reviewed logo exports and generate the renderer from the same SVG.
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const selection = require('../docs/branding/selection.json')
const catalog = require('../docs/branding/catalog.js')
if (!catalog.some(logo => logo.id === selection.id)) throw new Error('The selected logo is missing from the catalog')
const source = path.join(root, 'docs/branding/logos', selection.id)
const destination = path.join(root, 'src-tauri/icons')
fs.mkdirSync(destination, { recursive: true })
for (const name of fs.readdirSync(source)) {
  if (/\.png$/.test(name) || ['icon.ico', 'icon.icns'].includes(name)) fs.copyFileSync(path.join(source, name), path.join(destination, name))
}
for (const [from, to] of [
  ['icon.png', 'resources/icon.png'], ['icon.ico', 'resources/netmask.ico'], ['mark.svg', 'resources/netmask-icon.svg'],
  ['mark.svg', 'src/renderer/public/branding/mark.svg'], ['mark-light.svg', 'src/renderer/public/branding/mark-light.svg'],
  ['mark-mono.svg', 'src/renderer/public/branding/mark-mono.svg']
]) {
  const target = path.join(root, to)
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.copyFileSync(path.join(source, from), target)
}
const svg = fs.readFileSync(path.join(source, 'mark.svg'), 'utf8')
const shape = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  .replaceAll('stroke-width', 'strokeWidth').replaceAll('stroke-linecap', 'strokeLinecap').replaceAll('stroke-linejoin', 'strokeLinejoin')
  .replaceAll('stroke="#294e3f"', 'stroke={color}').replaceAll('fill="#294e3f"', 'fill={color}').replaceAll('"#ba5c3c"', '"var(--terracotta)"')
fs.writeFileSync(path.join(root, 'src/renderer/src/icons/BrandMark.tsx'), `// Generated by scripts/apply-branding.cjs from the selected SVG.\nimport React from 'react'\n\nexport const NetMaskLogoIcon = ({ size = 18, color = 'var(--accent)', className = '', style }: { size?: number; color?: string; className?: string; style?: React.CSSProperties }) => (\n  <svg className={className} style={style} width={size} height={size} viewBox="0 0 256 256" fill="none" aria-hidden="true" xmlns="http://www.w3.org/2000/svg">\n    ${shape}\n  </svg>\n)\n`)
console.log(`Applied ${selection.name} to the renderer, resources, and desktop icon formats.`)
